#!/usr/bin/env node
/**
 * Cloudflare Workers forbid compiling WebAssembly from bytes at runtime
 * ("Wasm code generation disallowed by embedder"). yoga-layout (used by
 * @react-pdf/renderer for PDF export) ships its wasm as an embedded base64
 * string and compiles it on load, so PDF export fails on Workers as-is.
 *
 * Before the OpenNext build this script, idempotently:
 *   1. extracts the embedded wasm to `dist/binaries/yoga.wasm`,
 *   2. adds `*.workerd.js` entries that import it as a pre-compiled module
 *      (`?module`, bundled by wrangler) and pass it via Emscripten's
 *      `instantiateWasm` hook,
 *   3. points yoga-layout's exports at those entries under the `workerd`
 *      condition only. Node (next dev / next build / Express) keeps the stock files.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// pnpm hard-links node_modules files to its global content-addressable store, so
// writing in place would also change the store's copy for every other project.
// Unlink first so each write gets a fresh inode local to this install.
function writeFresh(file, data) {
  fs.rmSync(file, { force: true });
  fs.writeFileSync(file, data);
}

// Resolve the yoga-layout copy @react-pdf/layout actually uses (pnpm is strict).
const fromApp = createRequire(path.join(appDir, 'package.json'));
const renderer = path.dirname(fromApp.resolve('@react-pdf/renderer/package.json'));
const fromRenderer = createRequire(path.join(renderer, 'package.json'));
const layout = path.dirname(fromRenderer.resolve('@react-pdf/layout/package.json'));
const fromLayout = createRequire(path.join(layout, 'package.json'));
const yogaDir = path.resolve(path.dirname(fromLayout.resolve('yoga-layout/load')), '../..');

const pkgPath = path.join(yogaDir, 'package.json');
const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
if (pkg.version !== '3.2.1') {
  console.warn(`[prepare-workerd-wasm] yoga-layout ${pkg.version} untested (expected 3.2.1); verify PDF export.`);
}

// 1. wasm bytes
const loaderJs = fs.readFileSync(path.join(yogaDir, 'dist/binaries/yoga-wasm-base64-esm.js'), 'utf8');
const match = /data:application\/octet-stream;base64,([A-Za-z0-9+/=]+)/.exec(loaderJs);
if (!match) throw new Error('[prepare-workerd-wasm] embedded yoga wasm not found');
const wasm = Buffer.from(match[1], 'base64');
if (wasm.readUInt32BE(0) !== 0x0061736d) throw new Error('[prepare-workerd-wasm] extracted bytes are not wasm');
writeFresh(path.join(yogaDir, 'dist/binaries/yoga.wasm'), wasm);

// 2. workerd entries
const shared = `import loadYogaImpl from '../binaries/yoga-wasm-base64-esm.js';
import yogaWasm from '../binaries/yoga.wasm?module';
import wrapAssembly from './wrapAssembly.js';

// Generated by apps/web/scripts/prepare-workerd-wasm.mjs: instantiate the
// pre-compiled module instead of compiling embedded bytes (blocked on Workers).
const instantiateWasm = (imports, receiveInstance) => {
  WebAssembly.instantiate(yogaWasm, imports).then((instance) => receiveInstance(instance, yogaWasm));
  return {};
};
const loadWorkerdYoga = async () => wrapAssembly(await loadYogaImpl({ instantiateWasm }));
`;
writeFresh(
  path.join(yogaDir, 'dist/src/load.workerd.js'),
  `${shared}
export async function loadYoga() {
  return loadWorkerdYoga();
}
export * from './generated/YGEnums.js';
`
);
writeFresh(
  path.join(yogaDir, 'dist/src/index.workerd.js'),
  `${shared}
const Yoga = await loadWorkerdYoga();
export default Yoga;
export * from './generated/YGEnums.js';
`
);

// 3. exports (workerd condition first; everything else unchanged)
pkg.exports = {
  '.': { workerd: './dist/src/index.workerd.js', default: './dist/src/index.js' },
  './load': { workerd: './dist/src/load.workerd.js', default: './dist/src/load.js' },
};
writeFresh(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);

console.log(`[prepare-workerd-wasm] yoga-layout patched for workerd (${wasm.length} B wasm) at ${yogaDir}`);
